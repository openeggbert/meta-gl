    using ::GLboolean;    ///< Boolean value (`GL_TRUE` / `GL_FALSE`), typically `unsigned char`.
    using ::GLbyte;       ///< Signed 8-bit integer.
    using ::GLchar;       ///< 8-bit character, used for shader source and info-log strings.
    using ::GLclampf;     ///< 32-bit float clamped to [0, 1].
    using ::GLenum;       ///< Unsigned 32-bit enumeration value.
    using ::GLfixed;      ///< Signed 32-bit fixed-point number (16.16 format).
    using ::GLfloat;      ///< 32-bit IEEE 754 floating-point.
    using ::GLhalf;       ///< 16-bit IEEE 754 half-precision floating-point.
    using ::GLint;        ///< Signed 32-bit integer.
    using ::GLint64;      ///< Signed 64-bit integer.
    using ::GLintptr;     ///< Signed integer wide enough to hold a pointer (for buffer offsets).
    using ::GLshort;      ///< Signed 16-bit integer.
    using ::GLsizei;      ///< Non-negative 32-bit integer for sizes and counts.
    using ::GLsizeiptr;   ///< Non-negative integer wide enough to hold a pointer (for buffer sizes).
    using ::GLsync;       ///< Opaque sync object handle (fence sync).
    using ::GLubyte;      ///< Unsigned 8-bit integer.
    using ::GLuint;       ///< Unsigned 32-bit integer; the raw type for most GL object names.
    using ::GLuint64;     ///< Unsigned 64-bit integer.
    using ::GLushort;     ///< Unsigned 16-bit integer.
    using ::GLvoid;       ///< Alias for `void`; used in some GL signatures for historical reasons.
