    /**
     * @brief Location of a uniform variable within a program object.
     *
     * Wraps the `GLint` returned by `glGetUniformLocation`.
     * The default value `-1` represents an invalid or absent location.
     */
    struct UniformLocation      { GLint  value{-1}; };

    /**
     * @brief Location (index) of a generic vertex attribute within a program object.
     *
     * Wraps the signed `GLint` returned by `glGetAttribLocation`; `-1`
     * represents an inactive or missing attribute. The unsigned constructor
     * keeps vertex-index call sites concise.
     */
    struct AttribLocation
    {
        GLint value{-1};

        constexpr AttribLocation() noexcept = default;
        constexpr explicit AttribLocation(GLint location) noexcept : value(location) {}
        constexpr explicit AttribLocation(GLuint location) noexcept
            : value(static_cast<GLint>(location))
        {
            assert(location <= static_cast<GLuint>(
                std::numeric_limits<GLint>::max()));
        }

        [[nodiscard]] constexpr bool valid() const noexcept { return value >= 0; }
        [[nodiscard]] constexpr explicit operator bool() const noexcept { return valid(); }
    };

    /**
     * @brief Enumeration index used by glGetActiveAttrib.
     *
     * Unlike @ref AttribLocation, this is an ordinal in the program's active
     * attribute list and is never the signed `-1` location sentinel.
     */
    struct ActiveAttribIndex
    {
        GLuint value{};
    };

    /**
     * @brief Index of an image unit used with `glBindImageTexture`.
     *
     * Wraps a `GLuint` image unit binding point index.
     */
    struct ImageUnit            { GLuint value{}; };

    /**
     * @brief Concept satisfied by a lightweight GL wrapper exposing a scalar
     *        `.value` convertible to `GLuint`.
     *
     * All handle structs defined in this header satisfy this concept.
     * It can be used to write generic functions that accept any meta-gl handle type.
     *
     * @tparam T  Type to check; must have a member `value` convertible to `GLuint`.
     *
     * @code
     * static_assert(GlHandle<TextureId>);   // true
     * static_assert(GlHandle<ShaderId>);    // true
     * static_assert(!GlHandle<GLuint>);     // false — raw scalar, not a handle struct
     * @endcode
     */
    template<typename T>
    concept GlHandle = requires(T h) {
        { h.value } -> std::convertible_to<GLuint>;
    };

    template<GlHandle T>
    [[nodiscard]] constexpr bool operator==(T lhs, T rhs) noexcept
    {
        return lhs.value == rhs.value;
    }

    /**
     * @brief Opt-in traits for enum classes that represent GL bit masks.
     *
     * `GLenum` and `GLbitfield` are commonly aliases of the same C++ type, so
     * their underlying type cannot distinguish domains. Enums.hpp explicitly
     * specializes this trait for real bitfield domains.
     */
    template<typename T>
    struct GlBitfieldTraits
    {
        static constexpr bool enabled = false;
        static constexpr GLbitfield all_bits = 0;
    };

    /**
     * @brief Concept satisfied only by explicitly registered GL bitfield enums.
     */
    template<typename T>
    concept GlBitfield =
        std::is_enum_v<T> &&
        GlBitfieldTraits<T>::enabled;

    /**
     * @brief Concept satisfied by non-bitfield `GLenum` enum classes.
     *
     * Used internally to constrain template parameters to typed GL enumerations.
     *
     * @tparam T  Enum type to check.
     *
     * Bitfield domains are excluded through the explicit
     * @ref metagl::GlBitfieldTraits
     * opt-in even when `GLenum` and `GLbitfield` are the same C++ type.
     */
    template<typename T>
    concept GlEnum =
        std::is_enum_v<T> &&
        std::same_as<std::underlying_type_t<T>, GLenum> &&
        !GlBitfield<T>;

    /**
     * @brief Concept satisfied by types safe for use in `std::span<const T>` GL data uploads.
     *
     * Requires trivial copyability and standard layout so the byte representation
     * is well-defined and can be passed directly to GL upload functions such as
     * `glBufferData`, `glTexImage2D`, etc.
     *
     * @tparam T  Type to check.
     *
     * @code
     * static_assert(SpanCompatible<float>);       // true
     * static_assert(SpanCompatible<glm::vec3>);   // true (assuming trivial + standard layout)
     * static_assert(!SpanCompatible<std::string>); // false
     * @endcode
     */
    template<typename T>
    concept SpanCompatible =
        std::is_trivially_copyable_v<T> &&
        std::is_standard_layout_v<T>;

